#!/usr/bin/env python3
"""Write docs/content-review.md: every subject, topic and item of the catalog,
for the owner's content review (one subject at a time). Re-run it after each
decision so the document always matches the catalog.

    python scripts/review_table.py
"""
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import catalog_lib as cl  # noqa: E402

OUT = cl.REPO / "docs" / "content-review.md"
JOBS = {"primary": "start here", "depth": "go deeper", "cross-check": "cross-check",
        "gap-filler": "fills a gap", "copy": "copy (rule)"}


def size(r):
    n = int(r["size_bytes"] or 0)
    if not n:
        return "?"
    return f"{n / 1e9:.1f} GB" if n >= 1e8 else f"{n / 1e6:.0f} MB"


def first_edition(r, sel):
    for ed in cl.BUNDLES:
        if r["id"] in sel[ed]:
            return ed
    return r["bundle"]


def main():
    _, rows = cl.read_csv(cl.CATALOG)
    pubs = {p["id"]: p for p in cl.read_csv(cl.PUBLISHERS)[1]}
    subjects = list(csv.DictReader(open(cl.SUBJECTS, encoding="utf-8")))
    coverage = list(csv.DictReader(open(cl.COVERAGE, encoding="utf-8")))
    sel = {ed: {r["id"] for r in cl.select(rows, ed)} for ed in cl.BUNDLES}
    o = ["# Content review\n\n",
         "Generated by `scripts/review_table.py` from the catalog; re-run it after each change. "
         "One subject at a time: for each topic, read what is there, then decide per item "
         "(keep / cut / other edition / replace) and what is missing (add). "
         "Write decisions in the **Decision** column or under **Missing / to add**; "
         "Claude then changes the catalog and re-runs this file.\n\n",
         "Columns: *Edition* = the smallest edition that carries it (each edition holds the ones before); "
         "*Role* = its job in the topic (start here, go deeper, cross-check, fills a gap); "
         "*About* = what is inside, from the catalog notes.\n"]
    for s in subjects:
        o.append(f"\n## {s['order']}. {s['label']}\n\n{s['description']}\n")
        for c in coverage:
            if c["subject"] != s["id"]:
                continue
            items = [r for r in rows if c["id"] in cl.topics(r)]
            o.append(f"\n### {c['id']} {c['domain']} ({c['status']})\n\n"
                     f"What it should answer: {c['must_answer']}.\n")
            if c.get("notes"):
                o.append(f"\nCoverage notes: {c['notes']}\n")
            if not items:
                o.append("\n*No items yet.*\n")
            else:
                o.append("\n| Item | Publisher, year | Size | Edition | Role | About | Decision |\n"
                         "|---|---|---|---|---|---|---|\n")
                for r in sorted(items, key=lambda r: (cl.BUNDLES.index(first_edition(r, sel))
                                                      if first_edition(r, sel) in cl.BUNDLES else 9, r["id"])):
                    home = "" if cl.topics(r)[:1] == [c["id"]] else " (also here)"
                    pub = pubs.get(r["publisher"], {}).get("name", r["publisher"]).split(" (")[0]
                    year = r["edition_or_date"][:30]
                    about = (r.get("about") or "").replace("|", "/")
                    shelf = "" if r["shelf"] in ("guides", "books") else f" [{r['shelf']}]"
                    o.append(f"| {r['id']} {(r['label'] or r['title']).replace('|', '/')}{shelf} | {pub}, {year} "
                             f"| {size(r)} | {first_edition(r, sel)} | {JOBS.get(r['job'], r['job'])}{home} "
                             f"| {about} | |\n")
            o.append("\n**Missing / to add:**\n")
    OUT.write_text("".join(o), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(cl.REPO)}")


if __name__ == "__main__":
    main()
